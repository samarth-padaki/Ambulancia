/*
* Try read data from model.
* 
*  @param data_out Output features. Output float[9].
*  @return IPWIN_RET_SUCCESS (0) or IPWIN_RET_NODATA (-1), IPWIN_RET_ERROR (-2), IPWIN_RET_STREAMEND (-3)
*/
int IMAI_dequeue(float *restrict data_out) {    
    __HOOK_REGION(true, 0);
    __RETURN_ERROR(fixwin_dequeue(_K2, _K1, 32000, 1600));
    __HOOK_REGION(false, 0);
    __HOOK_REGION(true, 1);
    __RETURN_ERROR(mtb_model_f32_to_quantized_int8(_K7, _K1, 128000, _K6, 9, _K5));
    __HOOK_REGION(false, 1);
    dequantize_d8_to_f32(_K6, data_out, 9, 0.00390625, -128);
    return 0;
}

/*
* Try write data to model.
* 
*  @param data_in Input features. Input float[4].
*  @return IPWIN_RET_SUCCESS (0) or IPWIN_RET_NODATA (-1), IPWIN_RET_ERROR (-2), IPWIN_RET_STREAMEND (-3)
*/
int IMAI_enqueue(const float *restrict data_in) {    
    __HOOK_REGION(true, 0);
    __RETURN_ERROR(fixwin_enqueue(_K2, data_in));
    __HOOK_REGION(false, 0);
    return 0;
}

